import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report

# 1. Create a synthetic dataset for demonstration
np.random.seed(42)
num_samples = 200
data = {
    'Feature1': np.random.randn(num_samples) * 10 + 50,
    'Feature2': np.random.randn(num_samples) * 5 + 20,
    'Label': np.random.choice(['Category A', 'Category B', 'Category C'], size=num_samples, p=[0.5, 0.3, 0.2])
}
df = pd.DataFrame(data)

# 2. Exploratory Data Analysis (EDA)
print("--- Exploratory Data Analysis (EDA) ---")
print("First 5 rows of the dataset:")
print(df.head())
print("\nDataset Summary Statistics:")
print(df.describe(include='all'))

# 3. Draw a Pie Chart of the Label distribution
plt.figure(figsize=(6, 6))
label_counts = df['Label'].value_counts()
plt.pie(label_counts, labels=label_counts.index, autopct='%1.1f%%', startangle=140, colors=sns.color_palette('pastel'))
plt.title('Distribution of Target Labels')
plt.show()

# 4. Split the Data into Train and Test sets
X = df[['Feature1', 'Feature2']]
y = df['Label']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42, stratify=y)
print(f"\nData split successful:")
print(f"Training set shape: {X_train.shape}")
print(f"Testing set shape: {X_test.shape}\n")

# 5. Train a Model & Find Accuracy
model = RandomForestClassifier(random_state=42)
model.fit(X_train, y_train)

y_pred = model.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)
print("--- Model Evaluation ---")
print(f"Model Accuracy: {accuracy * 100:.2f}%")
print("\nClassification Report:")
print(classification_report(y_test, y_pred))

# 6. Predict Actual Data and Compare with Original Labels
comparison_df = pd.DataFrame({
    'Actual Label': y_test.values,
    'Predicted Label': y_pred
})
print("--- Predictions vs Actual Labels (Sample) ---")
print(comparison_df.head(10))

import pickle

# Save the trained model to a file
model_filename = 'model.pkl'
with open(model_filename, 'wb') as file:
    pickle.dump(model, file)

print(f"Model successfully saved to {model_filename}")